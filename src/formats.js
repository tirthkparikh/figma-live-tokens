// Turn resolved tokens into CSS, SCSS, JS/TS, JSON and Tailwind (v3 preset and v4 @theme).
import { cssValue, normalType } from './tokens.js';

const isObj = v => v !== null && typeof v === 'object' && !Array.isArray(v);

export const kebab = s => String(s)
  .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
  .replace(/[^a-zA-Z0-9_-]+/g, '-')
  .replace(/^-+|-+$/g, '')
  .toLowerCase();

export const varName = (path, prefix = '') => '--' + [prefix, ...path].filter(Boolean).map(kebab).join('-');

const WHOLE_REF = /^\{([^{}]+)\}$/;

/** Per-token declarations: [[varName, value], ...]. Typography expands to several. */
function declarations(tokens, { prefix = '', refs = true } = {}) {
  const out = [];
  for (const tok of tokens.values()) {
    const name = varName(tok.path, prefix);
    const ref = refs && typeof tok.original === 'string' && tok.original.match(WHOLE_REF);
    const val = cssValue(tok);
    if (isObj(val)) {
      for (const [prop, v] of Object.entries(val)) {
        out.push([`${name}-${prop}`, ref ? `var(${varName(ref[1].trim().split('.'), prefix)}-${prop})` : v, tok]);
      }
    } else {
      out.push([name, ref && tokens.has(ref[1].trim()) ? `var(${varName(ref[1].trim().split('.'), prefix)})` : val, tok]);
    }
  }
  return out;
}

const block = (selector, decls, indent = '') =>
  `${indent}${selector} {\n${decls.map(([n, v]) => `${indent}  ${n}: ${v};`).join('\n')}\n${indent}}\n`;

/**
 * CSS custom properties. `themes` is { name: resolvedTokens }; only values that differ
 * from the base are written for each theme.
 */
export function css(tokens, { prefix, refs = true, themes = {}, selector = ':root', themeSelector = '[data-theme="{name}"]', classes = true } = {}) {
  const base = declarations(tokens, { prefix, refs });
  let out = `/* Generated by figma-live-tokens. Do not edit by hand. */\n${block(selector, base)}`;
  const baseMap = new Map(base.map(([n, v]) => [n, v]));
  for (const [name, themeTokens] of Object.entries(themes)) {
    const diff = declarations(themeTokens, { prefix, refs }).filter(([n, v]) => baseMap.get(n) !== v);
    if (!diff.length) continue;
    const sel = themeSelector.replaceAll('{name}', name);
    out += '\n' + block(sel, diff);
    if (name === 'dark') {
      out += `\n@media (prefers-color-scheme: dark) {\n${block(`${selector}:not([data-theme="light"])`, diff, '  ')}}\n`;
    }
  }
  if (classes) {
    const typo = [...tokens.values()].filter(t => normalType(t.type) === 'typography' && isObj(cssValue(t)));
    for (const t of typo) {
      const name = varName(t.path, prefix);
      const props = Object.keys(cssValue(t)).map(p => [p, `var(${name}-${p})`]);
      const rest = t.path.length > 1 && /^(typography|typo|type|text|font|fonts|text-styles?)$/i.test(kebab(t.path[0])) ? t.path.slice(1) : t.path;
      out += '\n' + block(`.typo-${rest.map(kebab).join('-')}`, props);
    }
  }
  return out;
}

export function scss(tokens, { prefix } = {}) {
  let out = '// Generated by figma-live-tokens. Do not edit by hand.\n';
  for (const tok of tokens.values()) {
    const name = '$' + varName(tok.path, prefix).slice(2);
    const val = cssValue(tok);
    if (isObj(val)) out += `${name}: (\n${Object.entries(val).map(([k, v]) => `  "${k}": ${String(v).includes(',') ? `(${v})` : v},`).join('\n')}\n);\n`;
    else out += `${name}: ${val};\n`;
  }
  return out;
}

function nest(tokens, leaf) {
  const root = {};
  for (const tok of tokens.values()) {
    let node = root;
    tok.path.slice(0, -1).forEach(seg => { node = node[seg] = isObj(node[seg]) ? node[seg] : {}; });
    node[tok.path.at(-1)] = leaf(tok);
  }
  return root;
}

export function js(tokens, { prefix } = {}) {
  const values = nest(tokens, cssValue);
  const vars = nest(tokens, t => (isObj(cssValue(t)) ? Object.fromEntries(Object.keys(cssValue(t)).map(p => [p, `var(${varName(t.path, prefix)}-${p})`])) : `var(${varName(t.path, prefix)})`));
  return {
    'tokens.js': `// Generated by figma-live-tokens. Do not edit by hand.\nexport const tokens = ${JSON.stringify(values, null, 2)};\n\nexport const vars = ${JSON.stringify(vars, null, 2)};\n\nexport default tokens;\n`,
    'tokens.cjs': `// Generated by figma-live-tokens. Do not edit by hand.\nconst tokens = ${JSON.stringify(values, null, 2)};\nconst vars = ${JSON.stringify(vars, null, 2)};\nmodule.exports = { tokens, vars, default: tokens };\n`,
    'tokens.d.ts': `// Generated by figma-live-tokens. Do not edit by hand.\nexport declare const tokens: ${JSON.stringify(values, null, 2)};\nexport declare const vars: ${JSON.stringify(vars, null, 2)};\nexport default tokens;\n`,
  };
}

export function json(tokens, { prefix } = {}) {
  const flat = {};
  for (const tok of tokens.values()) {
    const val = cssValue(tok);
    const key = varName(tok.path, prefix).slice(2);
    if (isObj(val)) for (const [p, v] of Object.entries(val)) flat[`${key}-${p}`] = v;
    else flat[key] = val;
  }
  return JSON.stringify(flat, null, 2) + '\n';
}

// ---- Tailwind ----

const CATEGORY_SEGMENT = /^(colou?rs?|palette|spacing|space|sizes?|sizing|radii|radius|border-?radius|rounded|corner-?radius|font-?sizes?|text|font-?famil(y|ies)|fonts?|font-?weights?|weights?|shadows?|box-?shadows?|elevation|line-?heights?|leading|letter-?spacing|tracking|breakpoints?|screens?|easing|ease|durations?|opacit(y|ies)|typography)$/i;

/** Which Tailwind theme bucket a token belongs to, or null to skip it. */
export function twCategory(tok) {
  const type = normalType(tok.type);
  const name = tok.path.map(kebab).join('-');
  switch (type) {
    case 'color': return 'color';
    case 'fontFamily': return 'font';
    case 'fontWeight': return 'font-weight';
    case 'shadow': return 'shadow';
    case 'cubicBezier': return 'ease';
    case 'duration': return 'duration';
    case 'lineHeight': return 'leading';
    case 'number': return /opacity/.test(name) ? 'opacity' : /line-?height|leading/.test(name) ? 'leading' : null;
    case 'dimension':
      if (/radius|rounded|corner/.test(name)) return 'radius';
      if (/font-?size|^text|type-?scale/.test(name)) return 'text';
      if (/line-?height|leading/.test(name)) return 'leading';
      if (/letter|tracking/.test(name)) return 'tracking';
      if (/breakpoint|screen/.test(name)) return 'breakpoint';
      if (/border-?width|stroke/.test(name)) return 'border-width';
      return 'spacing';
    default: return null;
  }
}

export function twKey(path) {
  const rest = path.length > 1 && CATEGORY_SEGMENT.test(kebab(path[0])) ? path.slice(1) : path;
  return rest.map(kebab).join('-') || 'DEFAULT';
}

const TW3_BUCKET = {
  color: 'colors', font: 'fontFamily', 'font-weight': 'fontWeight', shadow: 'boxShadow', ease: 'transitionTimingFunction',
  duration: 'transitionDuration', leading: 'lineHeight', opacity: 'opacity', radius: 'borderRadius', text: 'fontSize',
  tracking: 'letterSpacing', breakpoint: 'screens', 'border-width': 'borderWidth', spacing: 'spacing',
};

/** Tailwind v3 preset. Values point at CSS variables so live updates restyle utilities too. */
export function tailwind3(tokens, { prefix } = {}) {
  const extend = {};
  for (const tok of tokens.values()) {
    const cat = twCategory(tok);
    if (!cat || isObj(cssValue(tok))) continue;
    const bucket = TW3_BUCKET[cat];
    // screens can't use CSS variables inside media queries
    const value = cat === 'breakpoint' ? cssValue(tok) : `var(${varName(tok.path, prefix)})`;
    (extend[bucket] ??= {})[twKey(tok.path)] = cat === 'font' ? [value] : value;
  }
  return `// Generated by figma-live-tokens. Do not edit by hand.\n// Use as a preset: presets: [require('./tailwind.preset.cjs')]\nmodule.exports = { theme: { extend: ${JSON.stringify(extend, null, 2)} } };\n`;
}

/** Tailwind v4 CSS-first config: @theme inline mapping to the token variables. */
export function tailwind4(tokens, { prefix } = {}) {
  const inline = [], direct = [];
  for (const tok of tokens.values()) {
    const cat = twCategory(tok);
    if (!cat || cat === 'opacity' || cat === 'duration' || cat === 'border-width' || isObj(cssValue(tok))) continue;
    const twName = `--${cat}-${twKey(tok.path)}`.replace(/-DEFAULT$/, '');
    const ours = varName(tok.path, prefix);
    // Same name as ours: define it directly (a var() to itself would be circular).
    if (twName === ours || cat === 'breakpoint') direct.push([twName, cssValue(tok)]);
    else inline.push([twName, `var(${ours})`]);
  }
  let out = '/* Generated by figma-live-tokens. Do not edit by hand.\n   Import after tailwindcss:  @import "tailwindcss"; @import "./tokens.css"; @import "./tailwind.theme.css"; */\n';
  if (inline.length) out += block('@theme inline', inline);
  if (direct.length) out += (inline.length ? '\n' : '') + block('@theme', direct);
  return out;
}

export const FORMATS = ['css', 'scss', 'js', 'json', 'tailwind', 'tailwind4'];

/** Build every requested format. Returns { filename: contents }. */
export function render(tokens, { formats = ['css'], themes = {}, ...opts } = {}) {
  const files = {};
  for (const f of formats) {
    switch (f) {
      case 'css': files['tokens.css'] = css(tokens, { ...opts, themes }); break;
      case 'scss': files['_tokens.scss'] = scss(tokens, opts); break;
      case 'js': Object.assign(files, js(tokens, opts)); break;
      case 'json': files['tokens.flat.json'] = json(tokens, opts); break;
      case 'tailwind': files['tailwind.preset.cjs'] = tailwind3(tokens, opts); break;
      case 'tailwind4': files['tailwind.theme.css'] = tailwind4(tokens, opts); break;
      default: throw new Error(`Unknown format "${f}". Use: ${FORMATS.join(', ')}`);
    }
  }
  return files;
}
